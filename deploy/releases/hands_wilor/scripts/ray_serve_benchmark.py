"""Open-loop offered-load benchmark driver script.

Usage (deterministic fake server for smoke/validation):
    python -m scripts.ray_serve_benchmark \\
        --api unidepth.infer \\
        --levels 1,4,16,64,256 \\
        --target-completed 20 \\
        --out /tmp/ego_bench_smoke \\
        --fake-server

Usage (live endpoints with preserved real payloads):
    python -m scripts.ray_serve_benchmark \\
        --api unidepth.infer \\
        --payload-dir /vePFS-Mindverse/.../ray_serve_payloads \\
        --levels 1,4,16,64,256 \\
        --target-completed 100 \\
        --out /tmp/ego_bench_run

The driver writes raw items.jsonl, levels.csv, batches.csv, manifest.json, and
run_manifest.json under <out>/<run_id>/. Plots are generated by
``scripts.ray_serve_benchmark_plots``.
"""
from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path

from ego_annotation.serving.benchmark.generator import OfferedLevel
from ego_annotation.serving.benchmark.manifest import (
    build_synthetic_hand_crops_manifest,
    build_synthetic_hand_images_manifest,
    build_synthetic_hawor_infiller_manifest,
    build_synthetic_hawor_tracks_manifest,
    build_synthetic_droid_create_session_manifest,
    build_synthetic_droid_finalize_manifest,
    build_synthetic_droid_push_frame_manifest,
    build_synthetic_media_manifest,
    build_synthetic_unidepth_manifest,
    PayloadManifest,
    load_payload_manifest,
)
from ego_annotation.serving.benchmark.runner import ApiBenchmarkPlan, BenchmarkRunner
from ego_annotation.serving.gateway import ModelServiceGateway, RetryPolicy
from ego_annotation.serving.router import ModelApiName, ModelServiceRouter


def build_manifest_for_api(
    api: ModelApiName,
    *,
    count: int,
    payload_dir: Path | None = None,
    allow_synthetic: bool = False,
) -> PayloadManifest:
    """Load a real per-model corpus, or build synthetic fixtures for ``--fake-server``.

    Live offered-load runs must consume a preserved, model-native payload source at
    ``<payload_dir>/<api>.json``. Its binary parts are read locally and saved into a
    path-free output manifest with recomputed content hashes. The synthetic builders
    exist only for deterministic fake-server tests; they are never an implicit live
    fallback. DROID source manifests must carry the create/push/finalize session IDs
    captured for that benchmark lifecycle.
    """
    if payload_dir is not None:
        return load_payload_manifest(payload_dir / f"{api.value}.json", expected_api=api, limit=count)
    if not allow_synthetic:
        raise ValueError("live benchmarks require --payload-dir with real per-model payload manifests")
    if api is ModelApiName.UNIDEPTH_INFER:
        return build_synthetic_unidepth_manifest(manifest_id=f"manifest-{api.value}", count=count)
    if api is ModelApiName.HANDS_DETECT:
        return build_synthetic_hand_images_manifest(manifest_id=f"manifest-{api.value}", count=count)
    if api is ModelApiName.WILOR_RECONSTRUCT:
        return build_synthetic_hand_crops_manifest(manifest_id=f"manifest-{api.value}", count=count)
    if api is ModelApiName.HAWOR_INFER_TRACKS:
        return build_synthetic_hawor_tracks_manifest(manifest_id=f"manifest-{api.value}", count=count)
    if api is ModelApiName.HAWOR_INFILLER_FILL:
        return build_synthetic_hawor_infiller_manifest(manifest_id=f"manifest-{api.value}", count=count)
    if api is ModelApiName.COSMOS3_REASON:
        return build_synthetic_media_manifest(manifest_id=f"manifest-{api.value}", count=count, api_name=api)
    if api is ModelApiName.DROID_CREATE_SESSION:
        return build_synthetic_droid_create_session_manifest(manifest_id=f"manifest-{api.value}", count=count)
    if api is ModelApiName.DROID_PUSH_FRAME:
        return build_synthetic_droid_push_frame_manifest(
            manifest_id=f"manifest-{api.value}", count=count,
            session_ids=tuple(f"session-seeded-{i:04d}" for i in range(max(1, count // 4))),
        )
    if api is ModelApiName.DROID_FINALIZE:
        return build_synthetic_droid_finalize_manifest(
            manifest_id=f"manifest-{api.value}",
            session_ids=tuple(f"session-seeded-{i:04d}" for i in range(max(1, count))),
        )
    raise ValueError(f"no manifest builder for {api!r}")


def _make_levels(api: ModelApiName, intensities: list[float], target_completed: int, max_offered: int) -> list[OfferedLevel]:
    return [
        OfferedLevel(
            api_name=api,
            offered_intensity_per_s=rate,
            target_completed=target_completed,
            max_offered=max_offered,
        )
        for rate in intensities
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Open-loop offered-load benchmark driver")
    parser.add_argument("--api", required=True, help="model API name, e.g. unidepth.infer")
    parser.add_argument("--levels", default="1,4,16,64,256", help="comma-separated offered intensities (work units/s)")
    parser.add_argument("--target-completed", type=int, default=100)
    parser.add_argument("--max-offered", type=int, default=400)
    parser.add_argument("--manifest-count", type=int, default=400, help="number of distinct payload items to use")
    parser.add_argument(
        "--payload-dir", type=Path,
        help="directory containing real <api>.json payload-source descriptors and binary parts; required unless --fake-server",
    )
    parser.add_argument("--out", required=True, help="output base directory")
    parser.add_argument("--run-id", default=None)
    parser.add_argument("--fake-server", action="store_true", help="use a deterministic in-process fake HTTP server")
    parser.add_argument("--serve-host", default="127.0.0.1")
    parser.add_argument("--max-attempts", type=int, default=3)
    parser.add_argument("--deadline-s", type=float, default=5.0)
    parser.add_argument("--wire-format", choices=("multipart", "envelope"), default="multipart", help="explicit transport treatment; multipart remains the default")
    args = parser.parse_args(argv)

    api = ModelApiName(args.api)
    if not args.fake_server and args.payload_dir is None:
        parser.error("--payload-dir is required for live benchmarks; synthetic payloads are limited to --fake-server")
    intensities = [float(x) for x in args.levels.split(",") if x.strip()]
    manifest = build_manifest_for_api(
        api, count=args.manifest_count, payload_dir=args.payload_dir, allow_synthetic=args.fake_server,
    )
    levels = _make_levels(api, intensities, args.target_completed, args.max_offered)
    plan = ApiBenchmarkPlan(api_name=api, manifest=manifest, offered_levels=tuple(levels))

    router = ModelServiceRouter.canonical()
    out_dir = Path(args.out)

    if args.fake_server:
        from ego_annotation.serving.benchmark.fakeserver import start_fake_server, FakeHttpProbeTransport, FakeHttpGatewayTransport

        async def _run() -> int:
            server = await start_fake_server(host=args.serve_host, port=0)
            gateway_transport = FakeHttpGatewayTransport(server.runner)
            probe_transport = FakeHttpProbeTransport(server.runner)
            try:
                # Point the API at the fake server via override.
                base = f"http://{args.serve_host}:{server.port}"
                run_router = router.with_overrides({api: f"{base}/{api.value}"})
                gateway = ModelServiceGateway(
                    run_router, gateway_transport, retry_policy=RetryPolicy(max_attempts=args.max_attempts, deadline_s=args.deadline_s),
                    wire_format=args.wire_format,
                )
                runner = BenchmarkRunner(
                    router=run_router, gateway=gateway, probe_transport=probe_transport,
                    base_dir=out_dir, generator=None,
                )
                result = await runner.run([plan], run_id=args.run_id)
                print(f"run_id={result.run_id}")
                print(f"run_dir={result.run_dir}")
                print(f"summaries={len(result.summaries)}")
                for s in result.summaries:
                    print(
                        f"  {s.api_name} offered={s.offered_intensity_per_s}/s "
                        f"completed={s.completed_count} rejected={s.rejected_count} "
                        f"throughput={s.throughput_work_units_per_s:.2f}wu/s "
                        f"p50={s.response_latency_p50_ms}ms p95={s.response_latency_p95_ms}ms "
                        f"batch_mean={s.batch_size_mean} loads={s.model_load_count_min}-{s.model_load_count_max}"
                    )
                return 0
            finally:
                await gateway_transport.aclose()
                await probe_transport.aclose()
                await server.stop()

        return asyncio.run(_run())

    # Live: use httpx transport.
    gateway = ModelServiceGateway.with_httpx(
        router, retry_policy=RetryPolicy(max_attempts=args.max_attempts, deadline_s=args.deadline_s), wire_format=args.wire_format,
    )

    async def _run_live() -> int:
        from ego_annotation.serving.benchmark.runner import EndpointProbeConfig
        from scripts._benchmark_live_transport import HttpxProbeTransport

        runner = BenchmarkRunner(router=router, gateway=gateway, probe_transport=HttpxProbeTransport(), base_dir=out_dir)
        result = await runner.run([plan], run_id=args.run_id)
        print(f"run_id={result.run_id}")
        print(f"run_dir={result.run_dir}")
        print(f"live_apis={list(result.run_manifest.live_apis)}")
        print(f"down_apis={list(result.run_manifest.down_apis)}")
        return 0

    return asyncio.run(_run_live())


if __name__ == "__main__":
    sys.exit(main())
